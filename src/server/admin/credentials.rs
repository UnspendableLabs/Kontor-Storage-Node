//! Who is allowed into `/admin`, and how the first person gets in.
//!
//! # Why there is a claim step at all
//!
//! `ADMIN_PASSWORD` used to be the only door, and leaving it unset meant there
//! was no door: the UI rendered and nothing behind it could be unlocked. That
//! was a coherent default while the UI was an optional convenience.
//!
//! It stops being coherent when the UI *is* the configuration channel. A node
//! that starts with no environment at all has to be reachable by somebody, or
//! zero configuration means a node nobody can ever finish setting up. So the
//! first boot mints a one-time setup token, the operator trades it for a
//! password, and the password is kept as an Argon2id hash next to the keystore.
//!
//! # What the token is worth, and what it is not
//!
//! It opens an *unconfigured* node — one with no key, nothing stored, nothing to
//! steal — and it dies the moment a password is set. That is a much smaller
//! thing than the password it produces, which is why it is acceptable for it to
//! be logged, or to sit in an environment variable.
//!
//! It is not nothing, though, and the honest statement belongs here rather than
//! in a README nobody reads: a token on the volume means anyone who can read the
//! volume can claim the UI. That is the same trust boundary as the file seal
//! slot in [`crate::crypto::keystore`], so it moves no line that was not already
//! there.
//!
//! # The three ways a token reaches an operator
//!
//! - **`KONTOR_SETUP_TOKEN`** — supplied. Nothing is generated, nothing is
//!   written, and **the token never appears in the logs**; only a fingerprint
//!   does, which is enough to tell which token is live without publishing it.
//!   This is the option for an operator who would rather not have a secret in
//!   their log stream, at the price of having one in their environment. It is a
//!   choice of *which* exposure, not an escape from both.
//! - **Generated** — the zero-configuration default. Written to `.setup-token`
//!   and printed in full on every boot until it is claimed, because an operator
//!   who missed the first-boot line must not be locked out of their own node.
//! - **Neither, because the node is already claimed** — the credential is the
//!   stored hash, and a `KONTOR_SETUP_TOKEN` still sitting in the environment is
//!   inert. The node says so once and asks for it to be removed.

