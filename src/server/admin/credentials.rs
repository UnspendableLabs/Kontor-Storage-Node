    #[cfg(unix)]
    #[tokio::test]
    #[serial_test::serial]
    async fn both_files_are_owner_only() {
        use std::os::unix::fs::PermissionsExt;

        let _guard = EnvGuard::capture();
        let dir = tempfile::tempdir().unwrap();
        let unclaimed = AdminCredential::load_or_bootstrap(dir.path(), &no_env_password())
            .await
            .unwrap();
        let token = std::fs::read_to_string(dir.path().join(SETUP_TOKEN_FILE)).unwrap();

        let mode = std::fs::metadata(dir.path().join(SETUP_TOKEN_FILE))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600, "{mode:o}");

        claim(dir.path(), &unclaimed, token.trim(), PASSWORD).unwrap();
        let mode = std::fs::metadata(dir.path().join(ADMIN_FILE))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600, "{mode:o}");
    }
