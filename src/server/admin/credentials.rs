    #[test]
    fn credentials_never_print_themselves() {
        assert_eq!(
            format!(
                "{:?}",
                AdminCredential::Env(AdminPassword::new(Some(PASSWORD)))
            ),
            "Env(<redacted>)"
        );
        assert_eq!(
            format!(
                "{:?}",
                AdminCredential::Stored {
                    phc: "$argon2id$secret".to_string()
                }
            ),
            "Stored(<redacted>)"
        );
        let rendered = format!(
            "{:?}",
            AdminCredential::Unclaimed {
                token: Zeroizing::new("the-token".to_string()),
                source: TokenSource::Env,
            }
        );
        assert!(!rendered.contains("the-token"), "{rendered}");
    }

    #[test]
    fn a_fingerprint_identifies_a_token_without_revealing_it() {
        let token = "a".repeat(64);
        assert_eq!(fingerprint(&token).len(), 8);
        assert_eq!(fingerprint(&token), fingerprint(&token));
        assert_ne!(fingerprint(&token), fingerprint(&"b".repeat(64)));
    }

    /// Argon2 verification must reject a hash it cannot parse rather than
    /// panicking or, worse, accepting.
    /// A blank `ADMIN_PASSWORD` must not become a node that lets anyone in by
