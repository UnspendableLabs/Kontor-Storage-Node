    async fn the_ui_can_be_turned_off_outright() {
        let _guard = EnvGuard::capture();
        let dir = tempfile::tempdir().unwrap();
        std::env::set_var(ADMIN_UI_DISABLED_ENV, "1");

        let credential = AdminCredential::load_or_bootstrap(dir.path(), &no_env_password())
            .await
            .unwrap();

        assert!(matches!(credential, AdminCredential::Disabled));
        assert!(!credential.is_enabled());
        assert!(!credential.is_unclaimed());
        assert!(!credential.verify(PASSWORD));
        assert!(!credential.verify_token("anything"));
        // Nothing was minted for a UI nobody can open.
        assert!(!dir.path().join(SETUP_TOKEN_FILE).exists());
    }

